import 'package:dio/dio.dart';

/// Отличает «сервер отверг сессию» от «сеть недоступна».
///
/// Только явный отказ сервера (401 — истёк/отозван/неверен refresh-токен,
/// 403 — доступ запрещён) означает, что учётные данные больше не годны и надо
/// разлогинивать. Любой сетевой сбой (нет ответа, таймаут, обрыв) — НЕ повод
/// выходить из аккаунта: иначе офлайн-запуск или обрыв сети выкидывают
/// пользователя на экран входа, пройти который без сети невозможно.
bool isSessionRejection(Object error) {
  if (error is! DioException) return false;
  final code = error.response?.statusCode;
  return code == 401 || code == 403;
}
