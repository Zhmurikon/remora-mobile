import 'package:dio/dio.dart';

/// Отличает «сеть недоступна» от «сервер ответил и отверг запрос».
///
/// Нет ответа (таймаут, обрыв, DNS, замкнутый предохранитель) — повод
/// сохранить изменение локально и отправить его при восстановлении связи.
/// Есть ответ (даже 4xx/5xx) — сервер увидел запрос и вынес решение,
/// повторять его молча нельзя.
bool isNetworkFailure(Object error) {
  return error is DioException && error.response == null;
}
